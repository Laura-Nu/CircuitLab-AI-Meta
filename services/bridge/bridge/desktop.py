class Runner:
    """Only safe, structured status events cross from the worker to the UI."""
    def __init__(self, events):
        self.events = events
        self.thread = None
        self.loop = None
        self.task = None
        self.stopping = threading.Event()

    @property
    def active(self):
        return self.thread is not None and self.thread.is_alive()

    def start(self, config):
        if self.active:
            return
        self.stopping.clear()
        def worker():
            async def session():
                self.loop = asyncio.get_running_loop()
                self.task = asyncio.current_task()
                if self.stopping.is_set():
                    return
                try:
                    await run(config, lambda state, data: self.events.put((state, data)))
                except asyncio.CancelledError:
                    pass
                except Exception:
                    self.events.put(("transport_error", {}))
            try:
                asyncio.run(session())
            finally:
                self.loop = None
                self.task = None
                self.events.put(("finished", {}))
        self.thread = threading.Thread(target=worker, daemon=True)
        self.thread.start()

    def stop(self):
        self.stopping.set()
        loop, task = self.loop, self.task
        if loop is not None and task is not None:
            try:
                loop.call_soon_threadsafe(task.cancel)
            except RuntimeError:
                pass


class BridgeWindow:
    def __init__(self, root, directory=None):
        self.root = root
        self.directory = Path(directory) if directory is not None else data_directory()
        self.events = queue.Queue()
        self.runner = Runner(self.events)
        self.credential = None
        self.port_values = {}
        self.language = tk.StringVar(value="ES")
        self.server = tk.StringVar(value=DEFAULT_URL)
        self.port = tk.StringVar()
        self.state = "idle"
        self.last_result = None
        self.terminal_error = False
        self.closing = False
        try:
            saved = load_settings(self.directory)
            if saved:
                self.credential = enrollment(json.dumps(saved))
                self.language.set(saved.get("language", "es").upper())
                self.server.set(saved.get("url", DEFAULT_URL))
                self.port.set(saved.get("serial_port", ""))
        except (OSError, ValueError, TypeError):
            self.state = "storage_error"
        self.build()
        self.find_ports()
        self.translate()
        root.protocol("WM_DELETE_WINDOW", self.close)
        root.after(100, self.poll)

    def t(self, key):
        return TEXT[self.language.get().lower()].get(key, TEXT[self.language.get().lower()]["error"])

    def label(self, parent, key, **options):
        widget = ttk.Label(parent, text=self.t(key), **options)
        self.translated.append((widget, key))
        return widget

    def build(self):
        self.root.title("CircuitLab Bridge")
        self.root.geometry("740x740")
        self.root.minsize(590, 520)
        icon = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent)) / "bridge-icon.png"
        if icon.exists():
            self.icon = tk.PhotoImage(file=str(icon))
            self.root.iconphoto(True, self.icon)
        style = ttk.Style(self.root)
        style.theme_use("clam")
        style.configure(".", font=("Segoe UI", 10), background="#151c23", foreground="#eef4f6")
        style.configure("TFrame", background="#151c23")
        style.configure("TLabel", background="#151c23", foreground="#eef4f6")
        style.configure("TButton", padding=8, foreground="#10171e", background="#6ce5bc")
        style.configure("TEntry", fieldbackground="#eef4f6", foreground="#10171e")
        style.configure("TCombobox", fieldbackground="#eef4f6", foreground="#10171e")
        style.map("TCombobox", fieldbackground=[("readonly", "#eef4f6")],
                  foreground=[("readonly", "#10171e")])
        self.root.configure(background="#151c23")
        self.translated = []
        canvas = tk.Canvas(self.root, background="#151c23", highlightthickness=0)
        scrollbar = ttk.Scrollbar(self.root, orient="vertical", command=canvas.yview)
        canvas.configure(yscrollcommand=scrollbar.set)
        scrollbar.pack(side="right", fill="y")
        canvas.pack(side="left", fill="both", expand=True)
        frame = ttk.Frame(canvas, padding=22)
        window = canvas.create_window((0, 0), window=frame, anchor="nw")
        canvas.bind("<Configure>", lambda event: canvas.itemconfigure(window, width=event.width))
        frame.bind("<Configure>", lambda _: canvas.configure(scrollregion=canvas.bbox("all")), add="+")
        self.root.bind("<MouseWheel>", lambda event: canvas.yview_scroll(-int(event.delta / 120), "units"))
        frame.columnconfigure(0, weight=1)
        top = ttk.Frame(frame)
        top.grid(row=0, column=0, sticky="ew")
        ttk.Label(top, text="CircuitLab Bridge", font=("Segoe UI", 21, "bold")).pack(side="left")
        self.languages = ttk.Combobox(top, textvariable=self.language, values=["ES", "EN"], state="readonly", width=4)
        self.languages.pack(side="right")
        self.languages.bind("<<ComboboxSelected>>", lambda _: self.translate())
        self.label(frame, "subtitle", wraplength=640).grid(row=1, column=0, sticky="w", pady=(6, 16))
        self.label(frame, "intro", wraplength=640, justify="left").grid(row=2, column=0, sticky="w")
        self.paste = ttk.Button(frame, command=self.paste_credential)
        self.paste.grid(row=3, column=0, sticky="w", pady=(15, 5))
        self.translated.append((self.paste, "paste"))
        self.credential_status = ttk.Label(frame, foreground="#6ce5bc")
        self.credential_status.grid(row=4, column=0, sticky="w")
        self.label(frame, "server").grid(row=5, column=0, sticky="w", pady=(12, 4))
        self.server_entry = ttk.Entry(frame, textvariable=self.server)
        self.server_entry.grid(row=6, column=0, sticky="ew")
        self.label(frame, "port").grid(row=7, column=0, sticky="w", pady=(12, 4))
        ports = ttk.Frame(frame)
        ports.grid(row=8, column=0, sticky="ew")
        ports.columnconfigure(0, weight=1)
        self.port_picker = ttk.Combobox(ports, textvariable=self.port, state="readonly")
        self.port_picker.grid(row=0, column=0, sticky="ew")
        self.refresh = ttk.Button(ports, command=self.find_ports)
        self.refresh.grid(row=0, column=1, padx=(8, 0))
        self.translated.append((self.refresh, "refresh"))
        self.connect_button = ttk.Button(frame, command=self.toggle)
        self.connect_button.grid(row=9, column=0, sticky="w", pady=(16, 10))
        self.progress = ttk.Progressbar(frame, mode="indeterminate")
        self.progress.grid(row=10, column=0, sticky="ew")
        self.status = ttk.Label(frame, wraplength=640, foreground="#6ce5bc")
        self.status.grid(row=11, column=0, sticky="w", pady=(10, 5))
        self.result_label = ttk.Label(frame, wraplength=640)
        self.result_label.grid(row=12, column=0, sticky="w", pady=(0, 12))
        self.label(frame, "scope", wraplength=640, justify="left").grid(row=13, column=0, sticky="w")
        self.label(frame, "saved", wraplength=640, justify="left").grid(row=14, column=0, sticky="w", pady=(12, 0))
        frame.bind("<Configure>", lambda event: self.resize(event.width-44))
        self.root.update_idletasks()

    def resize(self, width):
        for widget, _ in self.translated:
            if isinstance(widget, ttk.Label) and widget.cget("wraplength"):
                widget.configure(wraplength=max(300, width))
        self.status.configure(wraplength=max(300, width))
        self.result_label.configure(wraplength=max(300, width))

    def translate(self):
        for widget, key in self.translated:
            widget.configure(text=self.t(key))
        self.credential_status.configure(text=self.t("ready") if self.credential else self.t("missing"))
        self.status.configure(text=self.t(self.state))
        self.result_label.configure(text=self.t("last") if self.last_result is None else self.last_text())
        self.connect_button.configure(text=self.t("disconnect" if self.runner.active else "connect"))

    def last_text(self):
        data = self.last_result
        status = data.get("status", "error")
        # The point is a protocol ID, never arbitrary server text.
        point = data.get("point") if data.get("point") in ["TP1", "TP2", "TP3"] else ""
        return (point + " · " if point else "") + self.t(status if status in [
            "ok", "timeout", "disconnected", "out_of_range", "precondition_failed"] else "error")

    def find_ports(self):
        try:
            ports = list(list_ports.comports())
        except OSError:
            ports = []
        previous = self.port_values.get(self.port.get(), self.port.get())
        self.port_values = {f"{p.device} — {p.description}": p.device for p in ports}
        self.port_picker.configure(values=list(self.port_values))
        chosen = next((name for name, port in self.port_values.items() if port == previous), "")
        self.port.set(chosen or (next(iter(self.port_values)) if len(ports) == 1 else ""))

    def paste_credential(self):
        try:
            raw = self.root.clipboard_get()
            if len(raw) > 16384:
                raise ConfigurationError("credential")
            clean = enrollment(raw)
            self.credential = clean
            self.server.set(clean["url"])
            self.state = "idle"
            self.terminal_error = False
            self.translate()
        except (tk.TclError, ConfigurationError) as exc:
            code = str(exc) if isinstance(exc, ConfigurationError) else "credential"
            self.status.configure(text=self.t({"server": "server_error"}.get(code, code)))

    def toggle(self):
        if self.runner.active:
            self.runner.stop()
            return
        try:
            if self.credential is None:
                raise ConfigurationError("missing")
            config = configuration(self.credential, self.port_values.get(self.port.get(), ""),
                                   self.server.get(), self.language.get().lower(), self.directory)
            save_settings(self.directory, config)
        except ConfigurationError as exc:
            self.status.configure(text=self.t({"server": "server_error", "port": "port_error"}.get(str(exc), str(exc))))
            return
        except OSError:
            self.status.configure(text=self.t("storage_error"))
            return
        self.terminal_error = False
        self.state = "connecting"
        self.runner.start(config)
        for widget in [self.paste, self.refresh, self.languages, self.port_picker, self.server_entry]:
            widget.configure(state="disabled")
        self.translate()

    def poll(self):
        while not self.events.empty():
            state, data = self.events.get_nowait()
            if state == "result":
                self.last_result = data
            elif state in ["unauthorized", "transport_error"]:
                self.state = state
                self.terminal_error = True
            elif state in ["stopped", "finished"]:
                if not self.terminal_error:
                    self.state = "idle"
            else:
                self.state = state
        if self.runner.active:
            if self.state in ["connecting", "reading", "retrying"]:
                self.progress.start(12)
            else:
                self.progress.stop()
        else:
            self.progress.stop()
            for widget in [self.paste, self.refresh, self.server_entry]:
                widget.configure(state="normal")
            self.languages.configure(state="readonly")
            self.port_picker.configure(state="readonly")
        self.translate()
        if self.closing and not self.runner.active:
            self.root.destroy()
            return
        self.root.after(100, self.poll)

    def close(self):
        self.closing = True
        self.runner.stop()
        self.root.withdraw()


def instance_lock(directory):
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.CreateMutexW.argtypes = [ctypes.c_void_p, wintypes.BOOL, wintypes.LPCWSTR]
    kernel.CreateMutexW.restype = wintypes.HANDLE
    name = "Local\\CircuitLabBridge-" + hashlib.sha256(str(directory).encode()).hexdigest()[:20]
    handle = kernel.CreateMutexW(None, False, name)
    if not handle:
        raise OSError("Cannot create bridge instance lock")
    if ctypes.get_last_error() == 183:
        kernel.CloseHandle.argtypes = [wintypes.HANDLE]
        kernel.CloseHandle(handle)
        return None
    return handle


def self_test(report):
    from bridge.desktop_config import _protect
    import ssl
    import serial
    import websockets
    import tempfile
    root = tk.Tk()
    root.withdraw()
    with tempfile.TemporaryDirectory(prefix="circuitlab-bridge-check-") as directory:
        window = BridgeWindow(root, directory)
        for language in ["ES", "EN"]:
            window.language.set(language)
            window.translate()
            root.update_idletasks()
            assert window.connect_button.cget("text") == TEXT[language.lower()]["connect"]
        root.destroy()
    sample = b"CircuitLab credential storage self-check"
    assert _protect(_protect(sample), decrypt=True) == sample
    Path(report).write_text(json.dumps({
        "status": "ok", "version": VERSION, "tk": tk.TkVersion, "tls": ssl.OPENSSL_VERSION,
        "serial": serial.VERSION, "websockets": websockets.__version__, "protected_storage": True,
        "scope": "Executable dependencies only; no network connection or physical acquisition."
    }, indent=2), encoding="utf-8")


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--self-test-report":
        self_test(sys.argv[2])
        return
    root = tk.Tk()
    root.withdraw()
    directory = data_directory()
    handle = instance_lock(directory)
    if handle is None:
        messagebox.showinfo("CircuitLab Bridge", TEXT["es"]["existing"])
        root.destroy()
        return
    try:
        BridgeWindow(root, directory)
        root.deiconify()
        root.mainloop()
    finally:
        kernel = ctypes.WinDLL("kernel32")
        kernel.CloseHandle.argtypes = [wintypes.HANDLE]
        kernel.CloseHandle(handle)


if __name__ == "__main__":
    main()
