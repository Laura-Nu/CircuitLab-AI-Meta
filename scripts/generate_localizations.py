"""Validate ARB parity and generate the runtime lookup. No Flutter build step required."""

import argparse
import json
import re
from pathlib import Path


def generate(root):
    folder = root / "apps/client/lib/l10n"
    catalogs = {}
    for language in ("en", "es"):
        raw = json.loads((folder / f"app_{language}.arb").read_text(encoding="utf-8"))
        catalogs[language] = {key: value for key, value in raw.items() if not key.startswith("@")}
    if catalogs["en"].keys() != catalogs["es"].keys():
        raise ValueError("English and Spanish must have exactly the same message keys")
    for key, english in catalogs["en"].items():
        spanish = catalogs["es"][key]
        if not english or not spanish:
            raise ValueError(f"Empty translation: {key}")

        def placeholders(text):
            return set(re.findall(r"\{([a-zA-Z_]\w*)\}", text))

        if placeholders(english) != placeholders(spanish):
            raise ValueError(f"Placeholder mismatch: {key}")
    encoded = json.dumps(catalogs, ensure_ascii=False, indent=2).replace("$", r"\$")
    return (
        "// Generated by scripts/generate_localizations.py. Edit the ARB catalogs.\nconst localizedMessages = <String, Map<String, String>>"
        + encoded
        + ";\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    destination = root / "apps/client/lib/l10n/messages.g.dart"
    rendered = generate(root)
    if args.check:
        if destination.read_text(encoding="utf-8") != rendered:
            raise SystemExit("Localization output is stale. Run python scripts/generate_localizations.py")
    else:
        destination.write_text(rendered, encoding="utf-8")
